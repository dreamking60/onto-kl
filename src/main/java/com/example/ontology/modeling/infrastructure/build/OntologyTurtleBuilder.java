package com.example.ontology.modeling.infrastructure.build;

import com.example.ontology.modeling.domain.ExtractedOntology;
import com.example.ontology.modeling.domain.ExtractedOntology.ExtractedClass;
import com.example.ontology.modeling.domain.ExtractedOntology.ExtractedIndividual;
import com.example.ontology.modeling.domain.ExtractedOntology.ExtractedLiteral;
import com.example.ontology.modeling.domain.ExtractedOntology.ExtractedProperty;
import com.example.ontology.modeling.domain.ExtractedOntology.ExtractedRelation;
import com.example.ontology.modeling.domain.ExtractedOntology.SubClass;
import com.example.ontology.modeling.domain.GeneratedOntology;
import com.example.ontology.modeling.domain.exception.ModelingException;
import org.apache.jena.datatypes.RDFDatatype;
import org.apache.jena.datatypes.TypeMapper;
import org.apache.jena.rdf.model.Literal;
import org.apache.jena.rdf.model.Model;
import org.apache.jena.rdf.model.ModelFactory;
import org.apache.jena.rdf.model.Property;
import org.apache.jena.rdf.model.Resource;
import org.apache.jena.riot.Lang;
import org.apache.jena.riot.RDFDataMgr;
import org.apache.jena.vocabulary.OWL;
import org.apache.jena.vocabulary.RDF;
import org.apache.jena.vocabulary.RDFS;
import org.apache.jena.vocabulary.XSD;
import org.springframework.stereotype.Component;

import java.io.StringReader;
import java.io.StringWriter;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.Locale;
import java.util.Map;
import java.util.Set;

/**
 * Turns an {@link ExtractedOntology} into two valid Turtle documents:
 * a T-Box (classes, properties, axioms) and an A-Box (individuals, relations,
 * literals).  All IRIs are generated under the project namespace.
 */
@Component
public class OntologyTurtleBuilder {

    private static final String DCTERMS_SOURCE = "http://purl.org/dc/terms/source";
    public GeneratedOntology build(ExtractedOntology extraction, String namespace,
                                   String sourceName, boolean includeSource) {
        if (namespace == null || namespace.trim().isEmpty()) {
            throw new ModelingException("Namespace for the generated ontology is missing");
        }
        String ns = namespace.trim();
        if (!ns.endsWith("#") && !ns.endsWith("/")) {
            ns = ns + "#";
        }

        Model tbox = ModelFactory.createDefaultModel();
        Model abox = ModelFactory.createDefaultModel();
        configurePrefixes(tbox, ns);
        configurePrefixes(abox, ns);

        Resource ontology = tbox.createResource(stripFragment(ns));
        ontology.addProperty(RDF.type, OWL.Ontology);
        ontology.addProperty(RDFS.label, tbox.createLiteral("Generated ontology: " + safe(sourceName)));
        ontology.addProperty(RDFS.comment, tbox.createLiteral(
                "Generated by the document-driven ontology modeling module from '" + safe(sourceName) + "'."));
        if (includeSource && sourceName != null) {
            ontology.addProperty(tbox.createProperty(DCTERMS_SOURCE), tbox.createLiteral(sourceName));
        }

        NameRegistry names = new NameRegistry(ns);
        Map<String, Resource> classes = new LinkedHashMap<>();
        Map<String, Resource> objectProperties = new LinkedHashMap<>();
        Map<String, Resource> datatypeProperties = new LinkedHashMap<>();
        Map<String, Resource> individuals = new LinkedHashMap<>();

        // 1) Make sure every class referenced anywhere exists in the T-Box.
        for (ExtractedClass extractedClass : extraction.getClasses().values()) {
            ensureClass(tbox, names, classes, extractedClass.getName(),
                    extractedClass.getLabel(), extractedClass.getComment());
        }
        for (ExtractedProperty property : extraction.getObjectProperties().values()) {
            ensureClassIfPresent(tbox, names, classes, property.getDomain());
            ensureClassIfPresent(tbox, names, classes, property.getRange());
        }
        for (ExtractedProperty property : extraction.getDatatypeProperties().values()) {
            ensureClassIfPresent(tbox, names, classes, property.getDomain());
        }
        for (SubClass subClass : extraction.getSubClassOf()) {
            ensureClassIfPresent(tbox, names, classes, subClass.getSub());
            ensureClassIfPresent(tbox, names, classes, subClass.getSuperClass());
        }
        for (ExtractedIndividual individual : extraction.getIndividuals().values()) {
            ensureClassIfPresent(tbox, names, classes, individual.getClassName());
        }

        // 2) Object / datatype properties (including ones only used by facts).
        for (ExtractedProperty property : extraction.getObjectProperties().values()) {
            Resource resource = ensureObjectProperty(tbox, names, objectProperties, property.getName(),
                    property.getLabel(), property.getComment(), property.isTransitive(), property.isSymmetric());
            addDomainRange(tbox, resource, classes, property.getDomain(), property.getRange());
        }
        for (ExtractedProperty property : extraction.getDatatypeProperties().values()) {
            Resource resource = ensureDatatypeProperty(tbox, names, datatypeProperties, property.getName(),
                    property.getLabel(), property.getComment());
            addDomain(tbox, resource, classes, property.getDomain());
            addDatatypeRange(tbox, resource, property.getRange());
        }
        for (ExtractedRelation relation : extraction.getRelations()) {
            Resource predicate = ensureObjectProperty(tbox, names, objectProperties, relation.getPredicate(),
                    relation.getPredicate(), null, false, false);
            if (predicate == null) {
                throw new ModelingException("Cannot create object property for relation: " + relation.getPredicate());
            }
        }
        for (ExtractedLiteral literal : extraction.getLiterals()) {
            ensureDatatypeProperty(tbox, names, datatypeProperties, literal.getPredicate(),
                    literal.getPredicate(), null);
        }

        // 3) Sub-class axioms.
        for (SubClass subClass : extraction.getSubClassOf()) {
            Resource sub = ensureClass(tbox, names, classes, subClass.getSub(), subClass.getSub(), null);
            Resource sup = ensureClass(tbox, names, classes, subClass.getSuperClass(),
                    subClass.getSuperClass(), null);
            if (sub != null && sup != null && !sub.equals(sup)) {
                sub.addProperty(RDFS.subClassOf, sup);
            }
        }

        // 4) Individuals.
        for (ExtractedIndividual extractedIndividual : extraction.getIndividuals().values()) {
            Resource individual = ensureIndividual(abox, names, individuals, extractedIndividual.getName(),
                    extractedIndividual.getLabel(), extractedIndividual.getComment());
            String className = extractedIndividual.getClassName();
            if (className != null && !className.trim().isEmpty()) {
                Resource classResource = ensureClass(tbox, names, classes, className, className, null);
                individual.addProperty(RDF.type, classResource);
            }
            individual.addProperty(RDF.type, abox.createResource(OWL.NS + "NamedIndividual"));
        }

        // 5) Object facts.
        for (ExtractedRelation relation : extraction.getRelations()) {
            Resource subject = ensureIndividual(abox, names, individuals, relation.getSubject(),
                    relation.getSubject(), null);
            Resource object = ensureIndividual(abox, names, individuals, relation.getObject(),
                    relation.getObject(), null);
            Resource predicate = ensureObjectProperty(tbox, names, objectProperties, relation.getPredicate(),
                    relation.getPredicate(), null, false, false);
            subject.addProperty(abox.createProperty(predicate.getURI()), object);
        }

        // 6) Data facts.
        for (ExtractedLiteral literal : extraction.getLiterals()) {
            Resource subject = ensureIndividual(abox, names, individuals, literal.getSubject(),
                    literal.getSubject(), null);
            Resource predicate = ensureDatatypeProperty(tbox, names, datatypeProperties,
                    literal.getPredicate(), literal.getPredicate(), null);
            subject.addProperty(abox.createProperty(predicate.getURI()),
                    toLiteral(abox, literal.getValue(), literal.getDatatype(), literal.getLanguage()));
        }

        String tboxTurtle = write(tbox);
        String aboxTurtle = write(abox);
        validate(tboxTurtle, "T-Box");
        validate(aboxTurtle, "A-Box");

        return new GeneratedOntology(tboxTurtle, aboxTurtle, tbox.size(), abox.size(),
                classes.size(), objectProperties.size(), datatypeProperties.size(), individuals.size());
    }

    // ------------------------------------------------------------------
    // T-Box helpers
    // ------------------------------------------------------------------

    private static Resource ensureClass(Model tbox, NameRegistry names, Map<String, Resource> classes,
                                        String rawName, String label, String comment) {
        if (rawName == null || rawName.trim().isEmpty()) {
            return null;
        }
        String key = normalizeKey(rawName);
        Resource existing = classes.get(key);
        if (existing != null) {
            if (label != null && !label.trim().isEmpty() && existing.getProperty(RDFS.label) == null) {
                existing.addProperty(RDFS.label, tbox.createLiteral(label.trim()));
            }
            if (comment != null && !comment.trim().isEmpty() && existing.getProperty(RDFS.comment) == null) {
                existing.addProperty(RDFS.comment, tbox.createLiteral(comment.trim()));
            }
            return existing;
        }
        String iri = names.allocate("class", rawName);
        Resource resource = tbox.createResource(iri);
        resource.addProperty(RDF.type, OWL.Class);
        resource.addProperty(RDFS.label, tbox.createLiteral(safeLabel(label, rawName)));
        if (comment != null && !comment.trim().isEmpty()) {
            resource.addProperty(RDFS.comment, tbox.createLiteral(comment.trim()));
        }
        classes.put(key, resource);
        return resource;
    }

    private static void ensureClassIfPresent(Model tbox, NameRegistry names, Map<String, Resource> classes,
                                             String name) {
        if (name != null && !name.trim().isEmpty()
                && !"owl:Thing".equalsIgnoreCase(name.trim())
                && !"Thing".equalsIgnoreCase(name.trim())) {
            ensureClass(tbox, names, classes, name, name, null);
        }
    }

    private static Resource ensureObjectProperty(Model tbox, NameRegistry names,
                                                 Map<String, Resource> properties, String rawName,
                                                 String label, String comment,
                                                 boolean transitive, boolean symmetric) {
        if (rawName == null || rawName.trim().isEmpty()) {
            return null;
        }
        String key = normalizeKey(rawName);
        Resource existing = properties.get(key);
        if (existing != null) {
            return existing;
        }
        Resource resource = tbox.createResource(names.allocate("property", rawName));
        resource.addProperty(RDF.type, OWL.ObjectProperty);
        resource.addProperty(RDFS.label, tbox.createLiteral(safeLabel(label, rawName)));
        if (comment != null && !comment.trim().isEmpty()) {
            resource.addProperty(RDFS.comment, tbox.createLiteral(comment.trim()));
        }
        if (transitive) {
            resource.addProperty(RDF.type, OWL.TransitiveProperty);
        }
        if (symmetric) {
            resource.addProperty(RDF.type, OWL.SymmetricProperty);
        }
        properties.put(key, resource);
        return resource;
    }

    private static Resource ensureDatatypeProperty(Model tbox, NameRegistry names,
                                                   Map<String, Resource> properties, String rawName,
                                                   String label, String comment) {
        if (rawName == null || rawName.trim().isEmpty()) {
            return null;
        }
        String key = normalizeKey(rawName);
        Resource existing = properties.get(key);
        if (existing != null) {
            return existing;
        }
        Resource resource = tbox.createResource(names.allocate("property", rawName));
        resource.addProperty(RDF.type, OWL.DatatypeProperty);
        resource.addProperty(RDFS.label, tbox.createLiteral(safeLabel(label, rawName)));
        if (comment != null && !comment.trim().isEmpty()) {
            resource.addProperty(RDFS.comment, tbox.createLiteral(comment.trim()));
        }
        properties.put(key, resource);
        return resource;
    }

    private static void addDomainRange(Model tbox, Resource property, Map<String, Resource> classes,
                                       String domain, String range) {
        if (property == null) {
            return;
        }
        if (domain != null && !domain.trim().isEmpty()) {
            Resource resource = classes.get(normalizeKey(domain));
            if (resource != null) {
                property.addProperty(RDFS.domain, resource);
            }
        }
        if (range != null && !range.trim().isEmpty()) {
            Resource resource = classes.get(normalizeKey(range));
            if (resource != null) {
                property.addProperty(RDFS.range, resource);
            }
        }
    }

    private static void addDomain(Model tbox, Resource property, Map<String, Resource> classes,
                                  String domain) {
        if (property == null) {
            return;
        }
        if (domain != null && !domain.trim().isEmpty()) {
            Resource resource = classes.get(normalizeKey(domain));
            if (resource != null) {
                property.addProperty(RDFS.domain, resource);
            }
        }
    }

    private static void addDatatypeRange(Model tbox, Resource property, String range) {
        if (property == null || range == null || range.trim().isEmpty()) {
            return;
        }
        property.addProperty(RDFS.range, tbox.createResource(datatype(range).getURI()));
    }

    private static Resource ensureIndividual(Model abox, NameRegistry names, Map<String, Resource> individuals,
                                             String rawName, String label, String comment) {
        if (rawName == null || rawName.trim().isEmpty()) {
            throw new ModelingException("Individual without a name in extraction result");
        }
        String key = normalizeKey(rawName);
        Resource existing = individuals.get(key);
        if (existing != null) {
            return existing;
        }
        Resource resource = abox.createResource(names.allocate("individual", rawName));
        resource.addProperty(RDFS.label, abox.createLiteral(safeLabel(label, rawName)));
        if (comment != null && !comment.trim().isEmpty()) {
            resource.addProperty(RDFS.comment, abox.createLiteral(comment.trim()));
        }
        individuals.put(key, resource);
        return resource;
    }

    // ------------------------------------------------------------------
    // Serialisation / validation / literals
    // ------------------------------------------------------------------

    private static void configurePrefixes(Model model, String namespace) {
        model.setNsPrefix("", namespace);
        model.setNsPrefix("rdf", RDF.uri);
        model.setNsPrefix("rdfs", RDFS.uri);
        model.setNsPrefix("owl", OWL.NS);
        model.setNsPrefix("xsd", XSD.NS);
    }

    private static String write(Model model) {
        StringWriter writer = new StringWriter();
        RDFDataMgr.write(writer, model, Lang.TURTLE);
        return writer.toString();
    }

    private static void validate(String turtle, String label) {
        try {
            Model model = ModelFactory.createDefaultModel();
            RDFDataMgr.read(model, new StringReader(turtle), null, Lang.TURTLE);
        } catch (RuntimeException e) {
            throw new ModelingException("Generated " + label + " is not valid Turtle: " + e.getMessage(), e);
        }
    }

    private static Literal toLiteral(Model model, String value, String datatype, String language) {
        if (value == null) {
            return model.createLiteral("");
        }
        if (language != null && !language.trim().isEmpty()) {
            return model.createLiteral(value, language.trim());
        }
        RDFDatatype type = datatype(datatype);
        if (type == null || type.getURI().equals(XSD.xstring.getURI())) {
            return model.createLiteral(value);
        }
        return model.createTypedLiteral(value, type);
    }

    private static RDFDatatype datatype(String name) {
        if (name == null || name.trim().isEmpty()) {
            return type(XSD.xstring.getURI());
        }
        String value = name.trim().toLowerCase(Locale.ROOT);
        if (value.startsWith("xsd:")) {
            value = value.substring(4);
        }
        switch (value) {
            case "string":
                return type(XSD.xstring.getURI());
            case "integer":
            case "int":
            case "long":
                return type(XSD.integer.getURI());
            case "decimal":
            case "double":
            case "float":
                return type(XSD.decimal.getURI());
            case "boolean":
            case "bool":
                return type(XSD.xboolean.getURI());
            case "date":
                return type(XSD.date.getURI());
            case "datetime":
                return type(XSD.dateTime.getURI());
            default:
                return type(name.trim());
        }
    }

    private static RDFDatatype type(String uri) {
        try {
            return TypeMapper.getInstance().getSafeTypeByName(uri);
        } catch (RuntimeException e) {
            return TypeMapper.getInstance().getSafeTypeByName(XSD.xstring.getURI());
        }
    }

    private static String safeLabel(String label, String fallback) {
        return label != null && !label.trim().isEmpty() ? label.trim() : fallback;
    }

    private static String safe(String value) {
        return value == null ? "source document" : value;
    }

    private static String stripFragment(String namespace) {
        return namespace.endsWith("#") ? namespace.substring(0, namespace.length() - 1) : namespace;
    }

    private static String normalizeKey(String value) {
        return value == null ? "" : value.trim().toLowerCase(Locale.ROOT);
    }

    /** Allocates sanitised, unique local names for classes/properties/individuals. */
    private static final class NameRegistry {
        private final String namespace;
        private final Set<String> used = new LinkedHashSet<>();

        private NameRegistry(String namespace) {
            this.namespace = namespace;
        }

        private String allocate(String kind, String rawName) {
            String base = sanitize(rawName);
            String candidate = base;
            int suffix = 2;
            while (used.contains(candidate)) {
                candidate = base + "_" + kind.charAt(0) + suffix++;
            }
            used.add(candidate);
            return namespace + candidate;
        }

        private static String sanitize(String rawName) {
            String name = rawName == null ? "" : rawName.trim()
                    .replaceAll("[\\s\\p{Punct}]+", "_")
                    .replaceAll("[^\\p{L}\\p{N}_]", "_")
                    .replaceAll("_+", "_")
                    .replaceAll("^_+|_+$", "");
            if (name.isEmpty()) {
                name = "Entity_" + Math.abs(rawName == null ? 0 : rawName.hashCode());
            }
            if (Character.isDigit(name.charAt(0))) {
                name = "N_" + name;
            }
            return name;
        }
    }
}
